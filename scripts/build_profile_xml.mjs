import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
const result = await build({
  stdin: {
    contents: 'export { XMLParser, XMLValidator } from "fast-xml-parser";',
    resolveDir: process.cwd(),
  },
  bundle: true,
  write: false,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none",
  banner: {
    js: "// fast-xml-parser 5.11.2 and bundled dependencies; see vendor/LICENSE-profile-xml.txt. Generated by npm run vendor:profile.",
  },
});
const output = result.outputFiles[0].text;
const path = "vendor/profile-xml.mjs";
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== output)
    throw new Error(
      "Vendored profile XML parser is stale; run npm run vendor:profile",
    );
} else await writeFile(path, output);
