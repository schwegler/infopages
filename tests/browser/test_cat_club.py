"""Exercise the imported original games and local-clock boundaries."""
from pathlib import Path
import pytest
from playwright.sync_api import expect

@pytest.mark.parametrize('width,height', [(320,568),(390,844),(768,600),(1440,900),(1440,600)])
def test_original_cat_club(clean_page, site_url, width, height):
    page=clean_page
    page.set_viewport_size({'width':width,'height':height})
    page.clock.install(time=__import__('datetime').datetime(2026,10,19,16,59,50))
    page.clock.pause_at(__import__("datetime").datetime(2026,10,19,16,59,58))
    requests=[];page.on('request',lambda req:requests.append(req.url))
    page.goto(f'{site_url}/five_pm_cat_club.html')
    expect(page.locator('#seconds')).to_have_text('02')
    page.clock.run_for(1000)
    expect(page.locator('#seconds')).to_have_text('01')
    page.clock.run_for(1000)
    expect(page.locator('#hero-title')).to_have_text('It’s 5 PM. Go be a person.')
    expect(page.locator('.hero-art')).to_be_visible()
    assert page.locator('.hero-art').evaluate('(img)=>img.naturalWidth>0')
    page.locator('#blocks-toggle').click()
    expect(page.locator('#blocks-toggle')).to_have_text('Pause')
    before=page.locator('#blocks-board').evaluate('(c)=>c.toDataURL()')
    page.get_by_role('button',name='Hard drop',exact=True).click()
    assert page.locator('#blocks-board').evaluate('(c)=>c.toDataURL()') != before
    page.get_by_role('button',name='Drop one row',exact=True).click()
    assert int(page.locator('#blocks-score').inner_text())>0
    page.locator('#blocks-toggle').focus();page.keyboard.press('p')
    expect(page.locator('#blocks-toggle')).to_have_text('Resume playing')
    page.locator('[data-game="snake"]').click()
    page.locator('#snake-toggle').click()
    page.get_by_role('button',name='Turn up',exact=True).click()
    page.clock.run_for(130)
    page.locator('#snake-toggle').click()
    expect(page.locator('#snake-toggle')).to_have_text('Resume playing')
    page.locator('[data-game="sudoku"]').click()
    expect(page.get_by_role('gridcell')).to_have_count(81)
    empty=page.get_by_role('gridcell',name=__import__('re').compile('empty')).first
    label=empty.get_attribute('aria-label').split(':')[0]
    empty.click()
    page.locator('#number-pad button').first.click()
    expect(page.get_by_role('gridcell',name=__import__('re').compile(label+': 1'))).to_have_count(1)
    page.locator('#sudoku-erase').click()
    expect(page.get_by_role('gridcell',name=label+': empty',exact=True)).to_have_count(1)
    page.locator('#sudoku-check').click()
    expect(page.locator('#sudoku-message')).not_to_be_empty()
    page.locator('#new-game').click()
    expect(page.locator('#sudoku-message')).to_be_empty()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    assert all(url.startswith(site_url) for url in requests)
    out=Path('artifacts/cat-club');out.mkdir(parents=True,exist_ok=True)
    page.screenshot(path=str(out/f'sudoku-{width}-{height}.png'),full_page=True)
    page.locator('[data-game="blocks"]').click()
    page.evaluate('scrollTo(0,0)')
    page.screenshot(path=str(out/f'first-{width}-{height}.png'),full_page=True)

def test_cat_touch_controls_and_keyboard_scope(browser, site_url):
    context=browser.new_context(viewport={'width':390,'height':600},has_touch=True,reduced_motion='reduce')
    page=context.new_page();page.goto(f'{site_url}/five_pm_cat_club.html')
    page.locator('#blocks-toggle').tap()
    page.get_by_role('button',name='Drop one row',exact=True).tap()
    expect(page.locator('#blocks-score')).to_have_text('1')
    page.locator('header .brand').first.focus()
    page.keyboard.press('p')
    expect(page.locator('#blocks-toggle')).to_have_text('Pause')
    page.locator('[data-game="sudoku"]').tap()
    page.get_by_role('gridcell',name=__import__('re').compile('empty')).first.tap()
    page.locator('#sudoku-board .selected').focus()
    page.keyboard.press('1')
    expect(page.locator('#sudoku-board .selected')).to_have_text('1')
    expect(page.locator('#sudoku-board .selected')).to_be_focused()
    page.keyboard.press('Backspace')
    expect(page.locator('#sudoku-board .selected')).to_have_text('')
    context.close()

@pytest.mark.parametrize('zone',['UTC','America/Los_Angeles','Asia/Tokyo'])
def test_countdown_uses_device_timezone(browser,site_url,zone):
    from datetime import datetime
    from zoneinfo import ZoneInfo
    context=browser.new_context(timezone_id=zone)
    page=context.new_page()
    before=datetime(2026,10,19,16,59,50,tzinfo=ZoneInfo(zone))
    frozen=datetime(2026,10,19,16,59,58,tzinfo=ZoneInfo(zone))
    page.clock.install(time=before);page.clock.pause_at(frozen)
    page.goto(f'{site_url}/five_pm_cat_club.html')
    expect(page.locator('#hours')).to_have_text('00')
    expect(page.locator('#minutes')).to_have_text('00')
    expect(page.locator('#seconds')).to_have_text('02')
    page.clock.run_for(2000)
    expect(page.locator('#day-state')).to_have_text('YOU MADE IT')
    page.clock.set_fixed_time(datetime(2026,10,24,12,0,tzinfo=ZoneInfo(zone)))
    page.clock.run_for(1000)
    expect(page.locator('#day-state')).to_have_text('THE CATS ARE OFF DUTY')
    expect(page.locator('#clock-note')).to_have_text('Next countdown: Monday')
    context.close()
